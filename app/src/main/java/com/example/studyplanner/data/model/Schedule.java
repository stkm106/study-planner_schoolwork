package com.example.studyplanner.data.model;

public class Schedule {
    private long id;
    private Integer courseId; // Nullable
    private int dayOfWeek;    // 1 = Chủ Nhật, 2 = Thứ 2, ..., 7 = Thứ 7
    private String startTime; // Format HH:mm
    private String endTime;   // Format HH:mm
    private boolean isAutoGenerated; // false = Sinh viên tạo, true = Hệ thống gợi ý

    public Schedule() {}

    public Schedule(long id, Integer courseId, int dayOfWeek, String startTime, String endTime, boolean isAutoGenerated) {
        this.id = id;
        this.courseId = courseId;
        this.dayOfWeek = dayOfWeek;
        this.startTime = startTime;
        this.endTime = endTime;
        this.isAutoGenerated = isAutoGenerated;
    }

    public Schedule(Integer courseId, int dayOfWeek, String startTime, String endTime, boolean isAutoGenerated) {
        this.courseId = courseId;
        this.dayOfWeek = dayOfWeek;
        this.startTime = startTime;
        this.endTime = endTime;
        this.isAutoGenerated = isAutoGenerated;
    }

    public long getId() { return id; }
    public void setId(long id) { this.id = id; }

    public Integer getCourseId() { return courseId; }
    public void setCourseId(Integer courseId) { this.courseId = courseId; }

    public int getDayOfWeek() { return dayOfWeek; }
    public void setDayOfWeek(int dayOfWeek) { this.dayOfWeek = dayOfWeek; }

    public String getStartTime() { return startTime; }
    public void setStartTime(String startTime) { this.startTime = startTime; }

    public String getEndTime() { return endTime; }
    public void setEndTime(String endTime) { this.endTime = endTime; }

    public boolean isAutoGenerated() { return isAutoGenerated; }
    public void setAutoGenerated(boolean autoGenerated) { isAutoGenerated = autoGenerated; }
}