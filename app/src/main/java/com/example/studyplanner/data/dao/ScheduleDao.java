package com.example.studyplanner.data.dao;

import android.content.ContentValues;
import android.content.Context;
import android.database.Cursor;
import android.database.sqlite.SQLiteDatabase;

import com.example.studyplanner.data.database.DatabaseHelper;
import com.example.studyplanner.data.model.Schedule;

import java.util.ArrayList;
import java.util.List;

public class ScheduleDao {
    private SQLiteDatabase db;
    private DatabaseHelper dbHelper;

    public static final String TABLE_NAME = "study_schedules";
    public static final String COLUMN_ID = "id";
    public static final String COLUMN_COURSE_ID = "course_id";
    public static final String COLUMN_DAY_OF_WEEK = "day_of_week";
    public static final String COLUMN_START_TIME = "start_time";
    public static final String COLUMN_END_TIME = "end_time";
    public static final String COLUMN_IS_AUTO = "is_auto_generated";

    public ScheduleDao(Context context) {
        dbHelper = new DatabaseHelper(context);
    }

    public void open() {
        db = dbHelper.getWritableDatabase();
    }

    public void close() {
        if (dbHelper != null) {
            dbHelper.close();
        }
    }

    public long insertSchedule(Schedule schedule) {
        ContentValues values = new ContentValues();
        if (schedule.getCourseId() != null) {
            values.put(COLUMN_COURSE_ID, schedule.getCourseId());
        } else {
            values.putNull(COLUMN_COURSE_ID);
        }
        values.put(COLUMN_DAY_OF_WEEK, schedule.getDayOfWeek());
        values.put(COLUMN_START_TIME, schedule.getStartTime());
        values.put(COLUMN_END_TIME, schedule.getEndTime());
        values.put(COLUMN_IS_AUTO, schedule.isAutoGenerated() ? 1 : 0);

        return db.insert(TABLE_NAME, null, values);
    }

    public int updateSchedule(Schedule schedule) {
        ContentValues values = new ContentValues();
        if (schedule.getCourseId() != null) {
            values.put(COLUMN_COURSE_ID, schedule.getCourseId());
        } else {
            values.putNull(COLUMN_COURSE_ID);
        }
        values.put(COLUMN_DAY_OF_WEEK, schedule.getDayOfWeek());
        values.put(COLUMN_START_TIME, schedule.getStartTime());
        values.put(COLUMN_END_TIME, schedule.getEndTime());
        values.put(COLUMN_IS_AUTO, schedule.isAutoGenerated() ? 1 : 0);

        return db.update(TABLE_NAME, values, COLUMN_ID + " = ?", new String[]{String.valueOf(schedule.getId())});
    }

    public int deleteSchedule(long id) {
        return db.delete(TABLE_NAME, COLUMN_ID + " = ?", new String[]{String.valueOf(id)});
    }

    public int deleteAutoGeneratedSchedules() {
        return db.delete(TABLE_NAME, COLUMN_IS_AUTO + " = 1", null);
    }

    public List<Schedule> getSchedulesByDay(int dayOfWeek) {
        List<Schedule> list = new ArrayList<>();
        Cursor cursor = db.query(TABLE_NAME, null, COLUMN_DAY_OF_WEEK + " = ?",
                new String[]{String.valueOf(dayOfWeek)}, null, null, COLUMN_START_TIME + " ASC");

        if (cursor != null && cursor.moveToFirst()) {
            do {
                list.add(cursorToSchedule(cursor));
            } while (cursor.moveToNext());
            cursor.close();
        }
        return list;
    }

    public List<Schedule> getAllSchedules() {
        List<Schedule> list = new ArrayList<>();
        Cursor cursor = db.query(TABLE_NAME, null, null, null, null, null, COLUMN_DAY_OF_WEEK + " ASC, " + COLUMN_START_TIME + " ASC");

        if (cursor != null && cursor.moveToFirst()) {
            do {
                list.add(cursorToSchedule(cursor));
            } while (cursor.moveToNext());
            cursor.close();
        }
        return list;
    }

    private Schedule cursorToSchedule(Cursor cursor) {
        long id = cursor.getLong(cursor.getColumnIndexOrThrow(COLUMN_ID));
        Integer courseId = cursor.isNull(cursor.getColumnIndexOrThrow(COLUMN_COURSE_ID)) ?
                null : cursor.getInt(cursor.getColumnIndexOrThrow(COLUMN_COURSE_ID));
        int dayOfWeek = cursor.getInt(cursor.getColumnIndexOrThrow(COLUMN_DAY_OF_WEEK));
        String startTime = cursor.getString(cursor.getColumnIndexOrThrow(COLUMN_START_TIME));
        String endTime = cursor.getString(cursor.getColumnIndexOrThrow(COLUMN_END_TIME));
        boolean isAuto = cursor.getInt(cursor.getColumnIndexOrThrow(COLUMN_IS_AUTO)) == 1;

        return new Schedule(id, courseId, dayOfWeek, startTime, endTime, isAuto);
    }
}