package com.example.studyplanner.data.dao;

import android.content.ContentValues;
import android.content.Context;
import android.database.Cursor;
import android.database.sqlite.SQLiteDatabase;

import com.example.studyplanner.data.database.DatabaseHelper;
import com.example.studyplanner.data.model.Schedule;

import java.util.ArrayList;
import java.util.List;

public class ScheduleDao {
    private DatabaseHelper dbHelper;
    private SQLiteDatabase db;

    public ScheduleDao(Context context) {
        dbHelper = new DatabaseHelper(context);
    }

    public void open() {
        db = dbHelper.getWritableDatabase();
    }

    public void close() {
        if (dbHelper != null) {
            dbHelper.close();
        }
    }

    public long insertSchedule(Schedule schedule) {
        ContentValues values = new ContentValues();
        if (schedule.getCourseId() != null) {
            values.put("course_id", schedule.getCourseId());
        } else {
            values.putNull("course_id");
        }
        values.put("day_of_week", schedule.getDayOfWeek());
        values.put("start_time", schedule.getStartTime());
        values.put("end_time", schedule.getEndTime());
        values.put("is_auto_generated", schedule.isAutoGenerated() ? 1 : 0);

        return db.insert("study_schedules", null, values);
    }

    public List<Schedule> getAllSchedules() {
        List<Schedule> list = new ArrayList<>();
        Cursor cursor = db.rawQuery("SELECT * FROM study_schedules ORDER BY day_of_week ASC", null);

        if (cursor.moveToFirst()) {
            do {
                Schedule schedule = new Schedule();
                schedule.setId(cursor.getLong(cursor.getColumnIndexOrThrow("id")));

                Integer courseId = cursor.isNull(cursor.getColumnIndexOrThrow("course_id")) ?
                        null : cursor.getInt(cursor.getColumnIndexOrThrow("course_id"));
                schedule.setCourseId(courseId);

                schedule.setDayOfWeek(cursor.getInt(cursor.getColumnIndexOrThrow("day_of_week")));
                schedule.setStartTime(cursor.getString(cursor.getColumnIndexOrThrow("start_time")));
                schedule.setEndTime(cursor.getString(cursor.getColumnIndexOrThrow("end_time")));
                schedule.setAutoGenerated(cursor.getInt(cursor.getColumnIndexOrThrow("is_auto_generated")) == 1);

                list.add(schedule);
            } while (cursor.moveToNext());
        }
        cursor.close();
        return list;
    }
}